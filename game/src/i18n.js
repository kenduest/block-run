const MESSAGES = {
    en,
    "zh-Hant": zhHant,
    ja,
};

let currentLanguageSetting = "auto";
let currentLanguage = "en";
export let TEXT = MESSAGES.en;

export function normalizeLanguageSetting(value) {
    return SUPPORTED_LANGUAGE_OPTIONS.includes(value) ? value : "auto";
}

export function detectBrowserLanguage(language = navigator.language || navigator.languages?.[0] || "en") {
    const normalized = String(language).toLowerCase();
    if (normalized.startsWith("ja")) return "ja";
    if (normalized.startsWith("zh")) return "zh-Hant";
    return "en";
}

export function setLanguage(setting = "auto") {
    currentLanguageSetting = normalizeLanguageSetting(setting);
    currentLanguage = currentLanguageSetting === "auto" ? detectBrowserLanguage() : currentLanguageSetting;
    TEXT = MESSAGES[currentLanguage] || MESSAGES.en;
    return { setting: currentLanguageSetting, language: currentLanguage };
}

export function getLanguageSetting() {
    return currentLanguageSetting;
}

export function getCurrentLanguage() {
    return currentLanguage;
}

export function applyStaticText(root = document) {
    root.querySelectorAll("[data-i18n]").forEach(element => {
        element.textContent = textAt(element.dataset.i18n);
    });
    for (const attr of ["aria-label", "title"]) {
        root.querySelectorAll(`[data-i18n-${attr}]`).forEach(element => {
            element.setAttribute(attr, textAt(element.dataset[`i18n${toDatasetSuffix(attr)}`]));
        });
    }
}

export function textAt(path, fallback = "") {
    return path.split(".").reduce((value, key) => value?.[key], TEXT) ?? fallback;
}

export function joinText(items = []) {
    return items.filter(Boolean).join(TEXT.common.comma);
}

function toDatasetSuffix(attr) {
    return attr.split("-").map(part => part[0].toUpperCase() + part.slice(1)).join("");
}

